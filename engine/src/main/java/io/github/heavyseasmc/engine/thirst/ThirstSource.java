package io.github.heavyseasmc.engine.thirst;

/**
 * 口渴的来源。同一回合内每个来源最多触发一次，但三者可以叠加。
 *
 * <p><b>为什么是枚举 + 集合，而不是一个计数器。</b>
 * 计数器能表示「这回合渴了 2 次」，但表示不了「哪 2 次」，于是三件事做不了：
 *
 * <ol>
 *   <li><b>幂等性会丢。</b>战斗标记一回合每人最多一个 —— 打三架也只渴一次。
 *       集合天然做到这点；计数器要靠调用方记得别加两次，而那种约定迟早会破。</li>
 *   <li><b>按来源的缓解无法表达。</b>阳伞的效果模型是 {@code unit: thirst_source}，
 *       抵的是「一个来源」。将来若出现只挡某一类来源的物资，计数器就得推倒重来。</li>
 *   <li><b>M5 天候要加第四个来源。</b>加一个枚举常量是加法；
 *       而如果此刻写成 boolean 或 int，那时就是改类型。</li>
 * </ol>
 *
 * <p>集合还顺带给出了一条不变量：<b>单回合口渴次数上限恒等于本枚举的常量数</b>。
 * 规则基线在这一点上有两句话：「可在同一回合叠加（最多 3 次）」是确定的，
 * 而「口渴叠加没有上限」标着存疑标记。取前者 —— 它与卡面结构一致，
 * 且由类型系统保证，不需要运行期检查。
 */
public enum ThirstSource {

    /** 你划了船，且本张航海牌上有船桨图示。 */
    ROWED,

    /**
     * 你参与了战斗（含助拳），且本张航海牌上有战斗图示。
     *
     * <p>一回合最多算一次 —— 规则用「每人最多 1 个战斗标记」表达，
     * 这里用集合的幂等性表达，两者等价。
     */
    FOUGHT,

    /** 你的名字出现在本张航海牌的「口渴」名单里。 */
    NAMED,

    /**
     * 你这一回合喝过酒（{@code buff_size} 的 {@code side_effect: thirst_at_end_of_turn}）。
     *
     * <p>❗<b>它不看牌面</b>：船桨与战斗那两个来源要航海牌上印着对应图示才算数，
     * 而喝酒的口渴是酒自己带的副作用，与今天翻到哪张牌无关。
     *
     * <p>本枚举的类注释早就写着「M5 天候要加第四个来源，加一个枚举常量是加法」——
     * 第四个来源提前到了 M2，形状与那时的预期相同：{@code count()} 的上限由常量数给出，
     * 不变量因此也不需要改成新的数字（{@code Invariants} 用的就是 {@code values().length}）。
     */
    DRANK_RUM,

    /** 天候“炎热”让全员产生的一次口渴。 */
    WEATHER
}
